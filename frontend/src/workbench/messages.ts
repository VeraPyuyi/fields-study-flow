export function resolveLanguage(profile?: string, explicit?: string | null): Language {
  const value = explicit || profile || "zh-CN";
  return value === "en" || value.toLowerCase().startsWith("en-") ? "en" : value === "bilingual" ? "bilingual" : "zh-CN";
}
